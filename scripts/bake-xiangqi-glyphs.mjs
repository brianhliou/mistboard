// Bakes the xiangqi piece characters into SVG path data so server-side OG
// cards can draw them without any font installed (resvg in the prod container
// has no CJK fonts; <text> would render as tofu).
//
// Output: packages/board-render/src/generated/xiangqi-glyph-paths.ts
// (committed). Re-run only when the character set changes:
//   curl -sL -o /tmp/NotoSansCJKsc-Bold.otf \
//     "https://github.com/notofonts/noto-cjk/raw/main/Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Bold.otf"
//   node scripts/bake-xiangqi-glyphs.mjs /tmp/NotoSansCJKsc-Bold.otf
//   npx biome format --write packages/board-render/src/generated/xiangqi-glyph-paths.ts
//
// Source font: Noto Sans CJK SC Bold, SIL Open Font License 1.1 (outlines may
// be embedded and redistributed; see apps/web/public/fonts/CREDITS.md).

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

// Union of the traditional + simplified piece tables in
// apps/web/src/xiangqi-piece-sets.ts, plus the
// Fortress Xiangqi Treasure (寶 traditional / 宝 simplified).
const CHARS = [...new Set('帥仕相傌俥炮兵將士象馬車砲卒帅马车将寶宝')];

// Match the geometry of glyphMark() in xiangqi-piece-sets.ts: the character
// drawn at font-size 46, centered on (50, 50) of the 100-unit piece box.
const FONT_SIZE = 46;
const CENTER = 50;

const fontPath = process.argv[2];
if (!fontPath) {
  console.error('usage: node scripts/bake-xiangqi-glyphs.mjs <path-to-NotoSansCJKsc-Bold.otf>');
  process.exit(1);
}

const font = opentype.parse(readFileSync(fontPath).buffer);
const scale = FONT_SIZE / font.unitsPerEm;
const entries = [];
for (const char of CHARS) {
  const glyph = font.charToGlyph(char);
  if (glyph.index === 0) {
    console.error(`font has no glyph for ${char}`);
    process.exit(1);
  }
  const x = CENTER - (glyph.advanceWidth * scale) / 2;
  // Vertically center the em box on CENTER. getPath's y is the baseline and
  // SVG y grows downward, so: baseline = center + em-middle-above-baseline.
  const baseline = CENTER + ((font.ascender + font.descender) / 2) * scale;
  const path = glyph.getPath(x, baseline, FONT_SIZE);
  entries.push(`  '${char}': '${path.toPathData(1)}',`);
}

const out = `// GENERATED by scripts/bake-xiangqi-glyphs.mjs — do not edit by hand.
// Xiangqi piece characters as SVG path data (Noto Sans CJK SC Bold, OFL 1.1),
// normalized to the 100-unit piece box used by xiangqi-piece-sets.ts
// (font-size ${FONT_SIZE}, centered on ${CENTER},${CENTER}). Lets server-side
// OG cards draw the characters with zero font dependence.
export const XIANGQI_GLYPH_PATHS: Record<string, string> = {
${entries.join('\n')}
};
`;

const target = resolve(
  fileURLToPath(import.meta.url),
  '../../packages/board-render/src/generated/xiangqi-glyph-paths.ts',
);
writeFileSync(target, out);
console.log(`wrote ${CHARS.length} glyph paths to ${target}`);
